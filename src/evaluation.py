"""Evaluation utilities for the directed-transition study."""

from __future__ import annotations

from typing import Dict, Mapping, Sequence

import numpy as np
import pandas as pd
from sklearn.base import clone
from sklearn.calibration import calibration_curve
from sklearn.metrics import (
    average_precision_score,
    brier_score_loss,
    matthews_corrcoef,
    roc_auc_score,
)
from sklearn.model_selection import StratifiedGroupKFold


def calculate_metrics(y_true, y_prob, threshold: float = 0.5) -> dict:
    """Calculate the main test-set metrics."""
    y_true = np.asarray(y_true)
    y_prob = np.asarray(y_prob)
    y_pred = (y_prob >= threshold).astype(int)

    return {
        "AUROC": float(roc_auc_score(y_true, y_prob)),
        "AUPRC": float(average_precision_score(y_true, y_prob)),
        "MCC": float(matthews_corrcoef(y_true, y_pred)),
        "Brier": float(brier_score_loss(y_true, y_prob)),
    }


def calculate_bootstrap_difference(
    y_true,
    prob_a,
    prob_b,
    iterations: int = 200,
    random_state: int = 42,
):
    """Paired bootstrap difference in AUROC for the same test episodes."""
    rng = np.random.default_rng(random_state)
    y_true = np.asarray(y_true)
    prob_a = np.asarray(prob_a)
    prob_b = np.asarray(prob_b)

    indices = np.arange(len(y_true))
    deltas = []

    for _ in range(iterations):
        bs_idx = rng.choice(indices, size=len(indices), replace=True)
        y_bs = y_true[bs_idx]

        if np.unique(y_bs).size < 2:
            continue

        auc_a = roc_auc_score(y_bs, prob_a[bs_idx])
        auc_b = roc_auc_score(y_bs, prob_b[bs_idx])
        deltas.append(auc_a - auc_b)

    if not deltas:
        raise ValueError(
            "No valid bootstrap samples were available for AUROC comparison."
        )

    deltas = np.asarray(deltas)
    return (
        float(deltas.mean()),
        (
            float(np.percentile(deltas, 2.5)),
            float(np.percentile(deltas, 97.5)),
        ),
    )


def optimize_threshold_for_mcc(y_true, y_prob):
    """Select the threshold maximizing MCC over a 0.01-0.99 grid."""
    thresholds = np.linspace(0.01, 0.99, 100)
    y_true = np.asarray(y_true)
    y_prob = np.asarray(y_prob)

    best_mcc = -1.0
    best_threshold = 0.5

    for threshold in thresholds:
        prediction = (y_prob >= threshold).astype(int)
        score = matthews_corrcoef(y_true, prediction)

        if score > best_mcc:
            best_mcc = score
            best_threshold = threshold

    return float(best_threshold), float(best_mcc)


def get_oof_predictions_for_threshold(
    model,
    X_train: pd.DataFrame,
    y_train,
    groups,
    n_splits: int = 5,
    random_state: int = 42,
):
    """Generate group-aware OOF probabilities for threshold selection."""
    splitter = StratifiedGroupKFold(
        n_splits=n_splits,
        shuffle=True,
        random_state=random_state,
    )

    X_train = X_train.reset_index(drop=True)
    y_train = pd.Series(y_train).reset_index(drop=True)
    groups = pd.Series(groups).reset_index(drop=True)

    oof_prob = np.full(len(y_train), np.nan, dtype=float)

    for fold, (fit_idx, validation_idx) in enumerate(
        splitter.split(X_train, y_train, groups=groups),
        start=1,
    ):
        fold_model = clone(model)
        fold_model.set_params(
            random_state=random_state + fold,
            n_jobs=-1,
        )
        fold_model.fit(
            X_train.iloc[fit_idx],
            y_train.iloc[fit_idx],
        )
        oof_prob[validation_idx] = fold_model.predict_proba(
            X_train.iloc[validation_idx]
        )[:, 1]

    if np.isnan(oof_prob).any():
        raise ValueError("OOF predictions contain missing values.")

    return oof_prob


def calibration_data(y_true, y_prob, n_bins: int = 10):
    """Return observed and predicted calibration coordinates."""
    observed, predicted = calibration_curve(
        y_true,
        y_prob,
        n_bins=n_bins,
        strategy="quantile",
    )
    return predicted, observed


def evaluate_locked_threshold(
    y_true,
    y_prob,
    threshold: float,
):
    """Calculate test MCC using a threshold locked before test evaluation."""
    prediction = (np.asarray(y_prob) >= threshold).astype(int)
    return float(matthews_corrcoef(y_true, prediction))


def run_statistical_evaluation(
    results: Mapping[str, dict],
    train_df: pd.DataFrame,
    test_df: pd.DataFrame,
    feature_sets: Mapping[str, Sequence[str]],
    targets: Sequence[str],
    bootstrap_iterations: int = 200,
) -> pd.DataFrame:
    """Reproduce the study's paired bootstrap and OOF threshold analysis.

    The `results` mapping is expected to contain model paths and test
    probabilities generated by the local training pipeline.
    """
    import joblib

    rows = []

    for target in targets:
        proposed_key = f"{target}_Proposed"
        baseline_key = f"{target}_Baseline"
        aggregate_key = f"{target}_Aggregate"

        if not all(k in results for k in [proposed_key, baseline_key]):
            continue

        proposed = results[proposed_key]
        baseline = results[baseline_key]

        if "prob_pred" not in proposed or "prob_pred" not in baseline:
            raise ValueError(
                "The training stage must retain test probabilities in memory "
                "before statistical evaluation."
            )

        y_true = np.asarray(proposed["prob_true"])
        prob_proposed = np.asarray(proposed["prob_pred"])
        prob_baseline = np.asarray(baseline["prob_pred"])

        delta_pb, ci_pb = calculate_bootstrap_difference(
            y_true,
            prob_proposed,
            prob_baseline,
            iterations=bootstrap_iterations,
            random_state=42,
        )

        if aggregate_key in results:
            prob_aggregate = np.asarray(results[aggregate_key]["prob_pred"])
            delta_pa, ci_pa = calculate_bootstrap_difference(
                y_true,
                prob_proposed,
                prob_aggregate,
                iterations=bootstrap_iterations,
                random_state=43,
            )
        else:
            delta_pa, ci_pa = np.nan, (np.nan, np.nan)

        model = joblib.load(proposed["model_path"])
        X_train = train_df[list(feature_sets["Proposed"])]
        y_train = train_df[target]
        groups_train = train_df["NationalCode"]

        oof_prob = get_oof_predictions_for_threshold(
            model,
            X_train,
            y_train,
            groups_train,
        )

        threshold, oof_mcc = optimize_threshold_for_mcc(
            y_train,
            oof_prob,
        )
        test_mcc = evaluate_locked_threshold(
            y_true,
            prob_proposed,
            threshold,
        )

        rows.append(
            {
                "Target": target,
                "Delta_AUROC_Proposed_vs_Baseline": delta_pb,
                "CI_Lower_PB": ci_pb[0],
                "CI_Upper_PB": ci_pb[1],
                "Delta_AUROC_Proposed_vs_Aggregate": delta_pa,
                "CI_Lower_PA": ci_pa[0],
                "CI_Upper_PA": ci_pa[1],
                "Optimal_Threshold_OOF": threshold,
                "OOF_MCC_at_Threshold": oof_mcc,
                "Test_MCC_at_Locked_Threshold": test_mcc,
            }
        )

    return pd.DataFrame(rows)
